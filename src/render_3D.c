/* Draw a single vertical wall slice (one screen column). */
static void	draw_column(t_game *game, t_ray ray, int column, bool vertical)
{
	float	wall_height;
	float	wall_start;
	float	wall_bottom;
	float	texture_step_y;
	float	texture_offset;
	float	texture_y;
	float	texture_x;

	wall_height =  (BLOCK_SIZE * HEIGHT) / ray.dist;
	texture_step_y = 32.0 / wall_height;
	texture_offset = 0;
	if (wall_height > HEIGHT)
	{
		texture_offset = (wall_height - HEIGHT) / 2.0;
		wall_height = HEIGHT;
	}

	// Center the wall slice vertically on screen.
	wall_start = (HEIGHT - wall_height) / 2;

	wall_bottom = wall_start + wall_height;
	texture_y = texture_offset * texture_step_y;
	if (vertical)
	{
		texture_x = (int)(ray.hit.y / 2.0) % 32;
		if (ray.orientation == WEST)
			texture_x = 31 - texture_x;
	}
	else {
		texture_x = (int)(ray.hit.x / 2.0) % 32;
		if (ray.orientation == SOUTH)
			texture_x = 31 - texture_x;
	}
	texture_y += 32;
	while (wall_start < wall_bottom)
	{
		float color = all_textures[(int) texture_y * 32 + (int) texture_x];
		my_mlx_pixel_put(game->img, column, wall_start, color == 1? BLACK : WHITE);
		texture_y += texture_step_y;
		wall_start++;
	}
}

/* Render the 3D field of view using raycasting. */
void	draw_3D_FOV(t_game *game)
{
	// Angle difference between each screen column ray.
	const float	angle_step = degrees_to_radians(60) / WIDTH;
	float		ray_angle;
	t_ray		h_ray;
	t_ray		v_ray;
	int			column;

	ray_angle = normalize_angle(game->player.angle - degrees_to_radians(30));
	column = 0;
	while (column < WIDTH)
	{
		h_ray = calculate_ray_distance_h(game, ray_angle);
		v_ray = calculate_ray_distance_v(game, ray_angle);
		if (v_ray.dist < h_ray.dist)
			draw_column(game, v_ray, column, true);
		else
			draw_column(game, h_ray, column, false);
		ray_angle = normalize_angle(ray_angle + angle_step);
		column++;
	}
}

void	draw_minimap(t_game *game)
{
	int start;
	float block_size;

	block_size = floorf((float)BLOCK_SIZE / 4);
	start = WIDTH - (int)(game->map.width * block_size);
	draw_map(game, block_size, start, true);
};
